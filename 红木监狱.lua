local function isTextInstance(inst)
    return inst:IsA("TextLabel") or inst:IsA("TextButton") or inst:IsA("TextBox")
end

local connected = setmetatable({}, { __mode = "k" })

local function translateInstanceText(inst)
    if not isTextInstance(inst) then return end
    if connected[inst] then return end
    connected[inst] = true

    local curr = inst.Text
    if type(curr) == "string" and V[curr] then
        inst:SetAttribute("_translating", true)
        inst.Text = V[curr]
        inst:SetAttribute("_translating", nil)
    end

    inst:GetPropertyChangedSignal("Text"):Connect(function()
        if inst:GetAttribute("_translating") then return end
        local newText = inst.Text
        if type(newText) == "string" and V[newText] then
            inst:SetAttribute("_translating", true)
            inst.Text = V[newText]
            inst:SetAttribute("_translating", nil)
        end
    end)
end

local function initForParent(parent)
    for _, desc in ipairs(parent:GetDescendants()) do
        if isTextInstance(desc) then
            translateInstanceText(desc)
        end
    end
end

